/**
 * Computes calibrated scenario-adjusted metrics for a given location and scenario key
 */
export function getCalibratedLocationData(locationId: string, scenarioKey: string) {
  const baseLoc = LOCATION_DATASETS[locationId] || LOCATION_DATASETS['kendrapara'];
  const scenario = SCENARIO_PRESETS[scenarioKey] || SCENARIO_PRESETS['varun-base'];

  // Apply multipliers
  const windNum = Math.round(145 * scenario.windMultiplier);
  const rainNum = Math.round(240 * scenario.rainMultiplier);
  const surgeNum = +(2.8 * scenario.surgeMultiplier).toFixed(1);

  // Recalculate assets risk scores
  const adjustedAssets = baseLoc.assets.map(asset => {
    let score = Math.min(99, Math.round(asset.riskScore * ((scenario.windMultiplier + scenario.rainMultiplier + scenario.surgeMultiplier) / 3)));
    let level: RiskLevel = 'LOW';
    if (score >= 80) level = 'CRITICAL';
    else if (score >= 60) level = 'HIGH';
    else if (score >= 40) level = 'MEDIUM';

    return {
      ...asset,
      riskScore: score,
      riskLevel: level,
      status: (score >= 80 ? 'At Risk' : score >= 60 ? 'Vulnerable' : 'Operational') as any,
    };
  });

  // Calculate KPIs
  const criticalAssets = adjustedAssets.filter(a => a.riskLevel === 'CRITICAL').length;
  const highRiskRoads = baseLoc.roads.filter(r => r.riskLevel === 'CRITICAL' || r.riskLevel === 'HIGH').length;
  const hospitalAccessRisks = adjustedAssets.filter(a => a.type === 'Hospital' && (a.riskLevel === 'CRITICAL' || a.riskLevel === 'HIGH')).length;
  const sheltersAtRisk = adjustedAssets.filter(a => a.type === 'Emergency Shelter' && (a.riskLevel === 'CRITICAL' || a.riskLevel === 'HIGH')).length;
  const powerRisks = adjustedAssets.filter(a => a.type === 'Power Substation' && (a.riskLevel === 'CRITICAL' || a.riskLevel === 'HIGH')).length;

  const adjustedPopulation = Math.round(baseLoc.populationAtRisk * ((scenario.rainMultiplier + scenario.surgeMultiplier) / 2));
  const adjustedWards = Math.min(36, Math.round(baseLoc.highRiskWards * scenario.surgeMultiplier));

  return {
    location: baseLoc,
    scenario,
    adjustedAssets,
    kpis: {
      assets: criticalAssets + Math.round(scenario.surgeMultiplier * 4),
      roads: highRiskRoads + (scenario.rainMultiplier > 1.2 ? 3 : 0),
      hospitals: hospitalAccessRisks,
      shelters: sheltersAtRisk + 2,
      power: powerRisks,
    },
    weather: {
      ...baseLoc.weather,
      windSpeed: `${windNum} km/h (Gusto ${windNum + 20})`,
      rainfall24h: `${rainNum} mm`,
      surgeHeight: `${surgeNum} m`,
      timeToImpact: scenario.timeToLandfall,
    },
    populationAtRisk: adjustedPopulation,
    highRiskWards: adjustedWards,
  };
}
